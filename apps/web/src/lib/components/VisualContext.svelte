<script lang="ts">
  import Icon from './Icon.svelte';
  import Disclosure from './Disclosure.svelte';
  import FrameGallery from './FrameGallery.svelte';
  import type { Primitive, Stage } from '../server/contracts';
  import {
    formatObservation,
    formatTime,
    galleryFrames,
    groupVisualObservations,
    type ImageEvidence,
  } from '../visual-presentation';

  let {
    stage,
    onseek,
    ontranscript,
  }: {
    stage: Stage;
    onseek: (ms: number) => void;
    ontranscript: (id: string) => void;
  } = $props();
  let groups = $derived(groupVisualObservations(stage));
  let speech = $derived(
    new Map(
      stage.primitives
        .filter(
          (p): p is Extract<Primitive, { kind: 'text' }> => p.kind === 'text',
        )
        .map((p) => [p.id, p]),
    ),
  );
  let remainingQuestions = $derived.by(() => {
    const shownAssets = new Set(
      groups.flatMap((group) => group.frames.map((frame) => frame.assetId)),
    );
    const images = stage.primitives.filter(
      (p): p is ImageEvidence => p.kind === 'image',
    );
    return (
      stage.context?.questions.filter(
        (q) => !stage.annotations.some((a) => a.questionId === q.id),
      ) ?? []
    ).map((question) => {
      const refs = new Set(
        question.searches.flatMap((search) => search.frameIds),
      );
      const frames = images.filter((frame) => refs.has(frame.id));
      const unseenAssets = new Set(
        frames
          .filter((frame) => !shownAssets.has(frame.assetId))
          .map((frame) => frame.assetId),
      );
      const newFrames = galleryFrames(
        images.filter((frame) => unseenAssets.has(frame.assetId)),
      );
      newFrames.forEach((frame) => shownAssets.add(frame.assetId));
      return { question, frames, newFrames };
    });
  });
  function transcriptLabel(id: string): string {
    const primitive = speech.get(id);
    if (!primitive) return 'Transcript';
    return primitive.locator.kind === 'media'
      ? `${primitive.speaker ?? 'Speech'} ${formatTime(primitive.locator.startMs)}`
      : (primitive.speaker ?? 'Source text');
  }
  function pipelineStep(text: string) {
    const parts = text.match(/^(.+?)\s+(\(.+\))$/);
    return { label: parts?.[1] ?? text, detail: parts?.[2] ?? '' };
  }
</script>

