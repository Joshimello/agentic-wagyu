                  {onseek}
                />
              </div>{/if}
            {#if entry.frames.length}<div class="search-frame-links">
                {#each entry.frames as frame}<a
                    href={`#frame-${frame.id}`}
                    title="View the captured evidence frame"
                    >Frame {formatTime(frame.actualMs ?? 0, true)}</a
                  >{/each}
              </div>{/if}
          </article>
        {/each}
      </Disclosure>
    </div>
  {/if}
